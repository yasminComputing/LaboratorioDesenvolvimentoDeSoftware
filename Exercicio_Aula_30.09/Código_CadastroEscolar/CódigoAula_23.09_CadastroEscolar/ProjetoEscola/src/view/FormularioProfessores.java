    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        if(!verificacaoPreenchimento()){
            return;
        }
        Professores p = new Professores();
        p.setNome(txtNome.getText() + "");
        p.setIdade(Integer.parseInt(txtIdade.getText() + ""));
        p.setDisciplina(txtDisciplina.getText() +"");
        
        ProfessoresDAO pdao= new ProfessoresDAO();
        
        pdao.inserir(p);
        JOptionPane.showMessageDialog(null,"Salvamento efetuado com sucesso","Mensagem",JOptionPane.INFORMATION_MESSAGE);

        limparCampos();
    }//GEN-LAST:event_btnCadastrarActionPerformed

