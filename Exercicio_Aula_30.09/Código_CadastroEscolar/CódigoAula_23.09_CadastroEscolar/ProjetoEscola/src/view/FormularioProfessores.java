    public boolean verificacaoPreenchimento() {
        if (txtNome.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "O campo não pode ser vazio");
            txtNome.requestFocus();
            return false;
        }
        if (txtIdade.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "O campo não pode ser vazio");
            txtIdade.requestFocus();
            return false;
        }
        try {
            Integer.parseInt(txtIdade.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "A idade deve conter apenas números.");
            txtIdade.requestFocus();
            return false;
        }
         if (txtDisciplina.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "O campo não pode ser vazio");
            txtIdade.requestFocus();
            return false;
         }
        return true;

    }

