    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {                                             
        String sexo = "Feminino";
        if(rdo_Masculino.isSelected()){
            sexo = "Masculino";
        }
        Aluno a = new Aluno(txtNome.getText(),txtDataNascimento.getText(),sexo,
                   Integer.parseInt(txtMatricula.getText()), cmb_cursos.getSelectedItem().toString(),txtCpf.getText(),txtEndereco.getText(),cmb_estados.getSelectedItem().toString(),txtTelefone.getText());
        
        JOptionPane.showMessageDialog(null,"Aluno cadastrado!","OK",JOptionPane.INFORMATION_MESSAGE);
        if(linhaEditar == -1){
            lista.add(a);
        }else{
            lista.set(linhaEditar,a);
            linhaEditar = -1;
        }
        carregarTabela();
        JOptionPane.showMessageDialog(null,"Dados salvos com sucesso!");
        
        limparCampos();
        arquivo.gravarArquivo();
        System.out.println("Aluno adicionado!");
        
        

    }                                            

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {                                           
        int linha = tbl_Alunos.getSelectedRow();
        if(linha == -1){
            JOptionPane.showMessageDialog(null,"Selecione um aluno na tabela","Atenção",JOptionPane.WARNING_MESSAGE);
            return;
        }
int resposta = JOptionPane.showConfirmDialog(null,"Deseja realmente excluir esta pessoa? ","Confirmação",JOptionPane.YES_NO_OPTION);        if(resposta == JOptionPane.YES_OPTION){
          lista.remove(linha);
          arquivo.gravarArquivo();
          
         DefaultTableModel tabela = (DefaultTableModel) tbl_Alunos.getModel();          
         tabela.removeRow(linha);
          System.out.println("Pessoa excluída!");
        }
    }                                          

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        int linha = tbl_Alunos.getSelectedRow();
        if(linha == -1){
            JOptionPane.showMessageDialog(null,"Selecione o aluno para editar");
            return;
        }
        linhaEditar = linha;
        Aluno a = lista.get(linha);
        
        txtNome.setText(a.getNome());
        txtCpf.setText(a.getCpf());
        txtEndereco.setText(a.getEndereco());
        cmb_cursos.setSelectedItem(a.getCurso());
        txtTelefone.setText(a.getTelefone());
        txtDataNascimento.setText(a.getDataNascimento());
      
        if(a.getSexo().equals("Masculino")){
            rdo_Masculino.setSelected(true);
        }else{
            rdo_Feminino.setSelected(true);
        }
        cmb_estados.setSelectedItem(a.getEstado());
        txtMatricula.setText(a.getMatricula() + "");
        
        System.out.println(lista.get(linha));
        
           
    }                                         

