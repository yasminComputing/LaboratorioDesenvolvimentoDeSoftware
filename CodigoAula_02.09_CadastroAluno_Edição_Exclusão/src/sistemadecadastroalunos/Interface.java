    public void carregarTabela(){
        DefaultTableModel tabela = (DefaultTableModel) tbl_Alunos.getModel();
        
        tabela.setRowCount(0);
        
        for(Aluno a: lista){
            tabela.addRow(a.obterDados());
        }
    }
